-- Tabla de categorías de recursos.
CREATE TABLE TCATEGORIAS (
    ID VARCHAR2(20) NOT NULL,
    DESCRIPCION VARCHAR2(200) NOT NULL,

    CONSTRAINT PK_TCATEGORIAS PRIMARY KEY (ID)
);

-- Secuencia para generar los números de las categorías.
CREATE SEQUENCE SEQ_CATEGORIAS
    START WITH 1
    INCREMENT BY 1
    NOCYCLE;
    
   
-- Recursos que se pueden reservar.
CREATE TABLE TRECURSOS (
    CODIGO VARCHAR2(50) NOT NULL,
    ID_CATEGORIA VARCHAR2(20) NOT NULL,
    DESCRIPCION VARCHAR2(200) NOT NULL,

    CONSTRAINT PK_TRECURSOS
        PRIMARY KEY (CODIGO),

    CONSTRAINT FK_TRECURSOS_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES TCATEGORIAS (ID)
);


CREATE TABLE TUSUARIOS (
    ID VARCHAR2(50) NOT NULL,
    NOMBRE VARCHAR2(150) NOT NULL,
    CLAVE VARCHAR2(255) NOT NULL,
    ROL VARCHAR2(20) NOT NULL,
    TELEFONO VARCHAR2(30),
    PRIMER_INGRESO NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_TUSUARIOS
        PRIMARY KEY (ID),

    CONSTRAINT CK_TUSUARIOS_ROL
        CHECK (ROL IN ('ADMINISTRADOR', 'FUNCIONARIO')),

    CONSTRAINT CK_TUSUARIOS_INGRESO
        CHECK (PRIMER_INGRESO IN (0, 1)),

    CONSTRAINT CK_TUSUARIOS_TELEFONO
        CHECK (ROL <> 'FUNCIONARIO' OR TELEFONO IS NOT NULL)
);
    
    
