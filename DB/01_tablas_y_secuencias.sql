CREATE TABLE TCATEGORIAS (
    ID VARCHAR2(20) NOT NULL,
    DESCRIPCION VARCHAR2(200) NOT NULL,

    CONSTRAINT PK_TCATEGORIAS PRIMARY KEY (ID)
);

-- Descripcion unica sin distinguir mayusculas ni espacios al inicio o al final.
CREATE UNIQUE INDEX UQ_TCATEGORIAS_DESCRIPCION
    ON TCATEGORIAS (UPPER(TRIM(DESCRIPCION)));

CREATE SEQUENCE SEQ_CATEGORIAS
    START WITH 1
    INCREMENT BY 1
    NOCYCLE;


CREATE TABLE TRECURSOS (
    CODIGO VARCHAR2(50) NOT NULL,
    ID_CATEGORIA VARCHAR2(20) NOT NULL,
    DESCRIPCION VARCHAR2(200) NOT NULL,

    CONSTRAINT PK_TRECURSOS PRIMARY KEY (CODIGO),

    CONSTRAINT FK_TRECURSOS_CATEGORIA
        FOREIGN KEY (ID_CATEGORIA)
        REFERENCES TCATEGORIAS (ID)
);


CREATE TABLE TUSUARIOS (
    ID VARCHAR2(50) NOT NULL,
    NOMBRE VARCHAR2(150) NOT NULL,
    -- Hash PBKDF2 "pbkdf2$iteraciones$sal$hash" (calculado en Java); nunca texto plano.
    CLAVE VARCHAR2(255) NOT NULL,
    ROL VARCHAR2(20) NOT NULL,
    TELEFONO VARCHAR2(30),
    PRIMER_INGRESO NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT PK_TUSUARIOS PRIMARY KEY (ID),

    CONSTRAINT CK_TUSUARIOS_ROL
        CHECK (ROL IN ('ADMINISTRADOR', 'FUNCIONARIO')),

    CONSTRAINT CK_TUSUARIOS_CLAVE
        CHECK (CLAVE LIKE 'pbkdf2$%'),

    CONSTRAINT CK_TUSUARIOS_INGRESO
        CHECK (PRIMER_INGRESO IN (0, 1)),

    CONSTRAINT CK_TUSUARIOS_TELEFONO
        CHECK (
            ROL <> 'FUNCIONARIO'
            OR TELEFONO IS NOT NULL
        )
);


CREATE TABLE TRESERVAS (
    ID NUMBER(10) NOT NULL,
    ID_USUARIO VARCHAR2(50) NOT NULL,
    DESCRIPCION_ACTIVIDAD VARCHAR2(500) NOT NULL,
    INICIO TIMESTAMP NOT NULL,
    FIN TIMESTAMP NOT NULL,
    ESTADO VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL,

    CONSTRAINT PK_TRESERVAS PRIMARY KEY (ID),

    CONSTRAINT FK_TRESERVAS_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES TUSUARIOS (ID),

    CONSTRAINT CK_TRESERVAS_ESTADO
        CHECK (ESTADO IN ('ACTIVA', 'CANCELADA')),

    CONSTRAINT CK_TRESERVAS_HORARIO
        CHECK (FIN > INICIO)
);

CREATE SEQUENCE SEQ_RESERVAS
    START WITH 1
    INCREMENT BY 1
    NOCYCLE;


CREATE TABLE TRESERVA_RECURSO (
    ID_RESERVA NUMBER(10) NOT NULL,
    CODIGO_RECURSO VARCHAR2(50) NOT NULL,

    CONSTRAINT PK_TRESERVA_RECURSO
        PRIMARY KEY (ID_RESERVA, CODIGO_RECURSO),

    CONSTRAINT FK_TRESERVAREC_RESERVA
        FOREIGN KEY (ID_RESERVA)
        REFERENCES TRESERVAS (ID),

    CONSTRAINT FK_TRESERVAREC_RECURSO
        FOREIGN KEY (CODIGO_RECURSO)
        REFERENCES TRECURSOS (CODIGO)
);